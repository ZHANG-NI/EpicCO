# ---- the instance generator: ONE source text, used here (verifier, tools) and written into the launcher ------------
GEN_SRC = r'''
import random as _random

_QL = [0.0, 0.10, 0.25, 0.50, 0.75, 0.90, 1.0]
_LONG = [350.0, 760.0, 980.0, 1230.0, 1720.0, 2010.0, 3200.0]       # long side of an item, mm
_ASP = [1.0, 1.25, 1.6, 2.25, 3.0, 4.0, 10.0]                       # long side / short side
_DEF_N = [0.20, 0.20, 0.20, 0.15, 0.10, 0.07, 0.04, 0.02, 0.02]     # defects on a plate: 0 .. 8
_DEF_S = [(1, 0.40), (2, 0.25), (3, 0.15), (4, 0.08), (5, 0.05), (8, 0.04), (15, 0.02), (40, 0.01)]
PARAM_ROWS = ["NAME;VALUE", "nPlates;100", "widthPlates;6000", "heightPlates;3210", "min1Cut;100", "max1Cut;3500",
              "min2Cut;100", "minWaste;20"]


def _q(table, u):
    for i in range(1, len(_QL)):
        if u <= _QL[i]:
            return table[i - 1] + (table[i] - table[i - 1]) * (u - _QL[i - 1]) / (_QL[i] - _QL[i - 1])
    return table[-1]


def _pick(rng, weights):
    u, acc = rng.random(), 0.0
    for i, w in enumerate(weights):
        acc += w
        if u < acc:
            return i
    return len(weights) - 1


def _between(rng, lo, hi):
    return int(lo) + int(rng.random() * (int(hi) - int(lo) + 1))


def gen_instance(fam, seed):
    """(batch rows, defect rows, parameter rows) of instance number `seed` of a family; rows are csv lines."""
    rng = _random.Random("%s/%d" % (fam["name"], int(seed)))
    n = _between(rng, fam["n"][0], fam["n"][1])
    scale = float(fam.get("scale", 1.0))
    dup = float(fam.get("dup", 0.5))
    sizes = []
    for i in range(n):
        if sizes and rng.random() < dup:                 # a size that is in the order book already; early sizes more often
            k = int(len(sizes) * rng.random() ** 2)
            sizes.append(sizes[k])
            continue
        long_ = min(3200.0, max(300.0, _q(_LONG, rng.random()) * scale))
        short = max(120.0, long_ / _q(_ASP, rng.random()))
        a, b = int(round(long_)), int(round(short))
        sizes.append((a, b) if rng.random() < 0.5 else (b, a))
    # stacks: a given number of them, or long chains for a share of the items and single items for the rest
    if fam.get("stacks"):
        k = _between(rng, fam["stacks"][0], fam["stacks"][1])
        cuts = sorted(_between(rng, 1, n - 1) for _ in range(k - 1)) if n > 1 else []
        lens = [b - a for a, b in zip([0] + cuts, cuts + [n]) if b > a]
    else:
        in_chains = int(round(n * float(fam.get("chain_share", 0.5))))
        lens = []
        while in_chains > 0:
            L = min(in_chains, _between(rng, fam["chain_len"][0], fam["chain_len"][1]))
            lens.append(L)
            in_chains -= L
        lens += [1] * (n - sum(lens))
        for i in range(len(lens) - 1, 0, -1):             # the stacks in a random order
            j = int(rng.random() * (i + 1))
            lens[i], lens[j] = lens[j], lens[i]
    batch = ["ITEM_ID;LENGTH_ITEM;WIDTH_ITEM;STACK;SEQUENCE"]
    it = 0
    for s, L in enumerate(lens):
        for q in range(L):
            batch.append("%d;%d;%d;%d;%d" % (it, sizes[it][0], sizes[it][1], s, q + 1))
            it += 1
    defects = ["DEFECT_ID;PLATE_ID;X;Y;WIDTH;HEIGHT"]
    d = 0
    for p in range(100):
        for _ in range(_pick(rng, _DEF_N)):
            w = _DEF_S[_pick(rng, [x[1] for x in _DEF_S])][0]
            h = _DEF_S[_pick(rng, [x[1] for x in _DEF_S])][0]
            w, h = max(1, int(w * (0.5 + rng.random()))), max(1, int(h * (0.5 + rng.random())))
            x, y = int(rng.random() * (6000 - w)), int(rng.random() * (3210 - h))
            defects.append("%d;%d;%d.0;%d.0;%d.0;%d.0" % (d, p, x, y, w, h))
            d += 1
    return batch, defects, list(PARAM_ROWS)


def materialise(fam, seed):
    """The three csv files of an instance as lists of lines (header first)."""
    if fam.get("kind") == "fixed":
        return list(fam["batch"]), list(fam["defects"]), list(fam["param"])
    return gen_instance(fam, seed)


def write_instance(directory, prefix, fam, seed):
    batch, defects, param = materialise(fam, seed)
    for name, rows in ((prefix + "_batch.csv", batch), (prefix + "_defects.csv", defects), ("global_param.csv", param)):
        with open(os.path.join(directory, name), "w", newline="") as f:
            f.write("".join(r + "\r\n" for r in rows))
'''
exec(GEN_SRC)       # defines gen_instance, materialise, write_instance, PARAM_ROWS


def load(path):
    with open(path, encoding="utf-8") as f:
        fam = json.load(f)
    if fam.get("kind") not in ("family", "fixed"):
        raise ValueError("not an instance file of this problem")
    return fam


def size(path):
    """Number of items: of the given instance, or the middle of a family's range."""
    fam = load(path)
    if fam["kind"] == "fixed":
        return len(fam["batch"]) - 1
    return (int(fam["n"][0]) + int(fam["n"][1])) // 2


def time_limit(n):
    return TIME_LIMIT_S


def io_slack(path):
    return 2.0


def seed_of(sol_path):
    """The seed of the run that wrote a solution file: the evaluation scripts put it into the file name (..__s<seed>.sol)."""
    m = re.search(r"__s(\d+)(?:__\d+)?\.sol$", os.path.basename(str(sol_path)))
    return int(m.group(1)) if m else None


def checker_path():
    cands = [os.environ.get("SE_GLASS_CHECKER"), shutil.which("cutcheck"),
             os.path.join(os.environ.get("SE_ROOT", ""), "common", "tools", "cutcheck"),
             os.path.join(os.path.expanduser("~"), "tools", "cutcheck")]
    for c in cands:
        if c and os.path.isfile(c) and os.access(c, os.X_OK):
            return c
    return None


def item_area(batch):
    a = 0
    for row in batch[1:]:
        f = row.split(";")
        a += int(f[1]) * int(f[2])
    return a


def verify(inst_path, sol_path, opts=None, seed=None):
    """{"ok", "cost", "msg"}: the solution goes through the official checker on the instance of (file, seed); the
    cost is the waste recomputed from the checker's number of plates and residual width."""
    tmp = None
    try:
        if not os.path.exists(sol_path) or os.path.getsize(sol_path) == 0:
            return {"ok": False, "cost": None, "msg": "no solution file"}
        fam = load(inst_path)
        if seed is None:
            seed = seed_of(sol_path)
        if seed is None and fam["kind"] == "family":
            return {"ok": False, "cost": None, "msg": "the seed of the run is not known (verify <instance> <solution> <seed>)"}
        chk = checker_path()
        if not chk:
            return {"ok": False, "cost": None, "msg": "the checker program (cutcheck) is not on this machine"}
        batch, defects, param = materialise(fam, seed or 0)
        P = dict(r.split(";")[:2] for r in param[1:])
        W, H = int(P["widthPlates"]), int(P["heightPlates"])
        tmp = tempfile.mkdtemp(prefix="gchk_")
        os.makedirs(os.path.join(tmp, "instances_checker"))
        os.makedirs(os.path.join(tmp, "logs"))
        write_instance(os.path.join(tmp, "instances_checker"), "X", fam, seed or 0)
        shutil.copyfile(sol_path, os.path.join(tmp, "instances_checker", "X_solution.csv"))
        subprocess.run([chk, "X", "0"], cwd=tmp, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=600)
        stat = os.path.join(tmp, "logs", "X_statistics.csv")
        if not os.path.exists(stat):
            return {"ok": False, "cost": None, "msg": "the checker gave no verdict (unreadable solution file)"}
        rows = [l.strip().split(";") for l in open(stat) if l.strip()]
        valid, plates, resid = rows[1][1] == "1", int(rows[1][2]), int(float(rows[1][4]))
        if not valid:
            return {"ok": False, "cost": None, "msg": "the checker rejects the solution (items, stack order, cut rules or defects)"}
        waste = plates * W * H - H * resid - item_area(batch)
        if waste <= 0:
            return {"ok": False, "cost": None, "msg": "waste %d: not a meaningful instance" % waste}
        return {"ok": True, "cost": float(waste), "msg": "", "plates": plates, "items": len(batch) - 1}
    except Exception as ex:
        return {"ok": False, "cost": None, "msg": "verifier: %r" % (ex,)}
    finally:
        if tmp:
            shutil.rmtree(tmp, ignore_errors=True)


def validate_instance(path, lo, hi):
    try:
        fam = load(path)
        batch, defects, param = materialise(fam, 1)
    except Exception as ex:
        return False, "unreadable: %r" % (ex,)
    n = len(batch) - 1
    if not (lo <= n <= hi):
        return False, "%d items outside %d..%d" % (n, lo, hi)
    for row in batch[1:]:
        f = [int(x) for x in row.split(";")]
        a, b = max(f[1], f[2]), min(f[1], f[2])
        if b < 100 or a > 3500 or b > 3210:
            return False, "an item of %d x %d cannot be cut out of a plate" % (a, b)
    return True, ""


def features(path):
    fam = load(path)
    batch, defects, param = materialise(fam, 1)
    n = len(batch) - 1
    stacks = len({r.split(";")[3] for r in batch[1:]})
    return {"n": n, "stacks": stacks, "plates_of_items": item_area(batch) / (6000.0 * 3210.0), "items_per_stack": n / float(max(1, stacks))}


def canonical(path_in, path_out, rng=None):
    shutil.copy(path_in, path_out)


def signature_of(batch):
    """[items, stacks, hash of the multiset of item sizes, hash of the stack lengths]: equal for two order books that
    are the same up to the numbering of items and stacks (used by the training / test overlap check)."""
    sizes = sorted((max(int(f[1]), int(f[2])), min(int(f[1]), int(f[2]))) for f in (r.split(";") for r in batch[1:]))
    st = {}
    for r in batch[1:]:
        st[r.split(";")[3]] = st.get(r.split(";")[3], 0) + 1
    return [len(sizes), len(st), hashlib.md5(repr(sizes).encode()).hexdigest(), hashlib.md5(repr(sorted(st.values())).encode()).hexdigest()]


def signature(path, seed=1):
    return signature_of(materialise(load(path), seed)[0])


def sig_similarity(a, b):
    return 1.0 if (a[0] == b[0] and a[2] == b[2]) else 0.0


