def run_cmd(bindir, inst_path, sol_path, T, seed, opts=None):
    return [os.path.join(bindir, "solver"), inst_path, sol_path, "-t", "%d" % max(1, int(T)), "-seed", str(seed)]


_LINE = re.compile(r"^RESULT items \d+ waste (\d+) plates \d+ solutions \d+ time_best ([0-9.]+)")


def trace(sol_path, stdout_path):
    """[[seconds, cost]]: the program prints one result line (waste, time of the best solution)."""
    try:
        for line in open(stdout_path, errors="ignore"):
            m = _LINE.match(line.strip())
            if m:
                return [[float(m.group(2)), float(m.group(1))]]
    except OSError:
        pass
    return []


def locked_violation(tree):
    """None, or why the tree is refused: an interface file differs from the original or is missing."""
    tree = Path(tree)
    for rel, md5 in LOCKED.items():
        p = tree / rel
        if not p.exists():
            return "BUILD REFUSED: %s is missing; it must stay exactly as in the original." % rel
        if hashlib.md5(p.read_bytes()).hexdigest() != md5:
            return ("BUILD REFUSED: %s differs from the original. This file (arguments, clock and output of the program, "
                    "or a helper header) must stay byte-identical; put your changes in the solver's own files under gc/ "
                    "and in params.txt." % rel)
    return None


def pack(prefix, out, name=None):
    """A given instance (<prefix>_batch.csv, <prefix>_defects.csv, global_param.csv next to them) as one .gfam file."""
    prefix = str(prefix)
    rd = lambda p: [l.rstrip("\r\n") for l in open(p, newline="") if l.strip()]
    fam = {"kind": "fixed", "name": name or os.path.basename(prefix), "batch": rd(prefix + "_batch.csv"),
           "defects": rd(prefix + "_defects.csv"), "param": rd(os.path.join(os.path.dirname(prefix) or ".", "global_param.csv"))}
    with open(out, "w", encoding="utf-8") as f:
        json.dump(fam, f)
    return fam


