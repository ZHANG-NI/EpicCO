#!/usr/bin/env python3
"""Glass cutting (two-dimensional guillotine cutting of rectangular items out of a sequence of large plates that carry
defects; the items of an order book come in stacks whose order must be kept; the objective is the WASTE: the area of
the plates used, the last one only up to its last vertical cut, minus the area of the items).

The solver is an open-source C++ tree search, used as published behind a small interface file (`host_main.cpp`,
LOCKED, with the two helper headers it is built on). It has NO random number: a run is a function of the instance and
of the time limit. Which of its searches runs is one line in `params.txt` (e.g. `MBA* c 1 f 1.5`).

Instance file (`<name>.gfam`, JSON), two kinds:
  {"kind": "family", "name": ..., <recipe>}   a FAMILY of order books: the SEED of a run selects the instance, which is
                                               generated by gen_instance() below (the same family and seed always
                                               give the same instance);
  {"kind": "fixed", "name": ..., "batch": [...], "defects": [...], "param": [...]}   one given instance, the lines of
                                               its three csv files as they are; the seed plays no role.
The launcher writes the three csv files of the instance, runs the program on them and removes them again.
Solution: the csv file of the cutting tree (PLATE_ID;NODE_ID;X;Y;WIDTH;HEIGHT;TYPE;CUT;PARENT).
Cost: every solution goes through the official checker of the problem (items, order in the stacks, cut rules,
defects); the waste is recomputed from the checker's number of plates and residual width, never taken from the
solver. Smaller is better."""
